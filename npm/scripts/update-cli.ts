// Usage: node scripts/update-cli.ts <tag>
//
// Writes the version and checksums of the jsr binaries of the given GitHub
// release to src/cli_version.ts.

import * as fs from "node:fs";
import * as path from "node:path";

const CLI_VERSION_FILE = path.join(
  import.meta.dirname,
  "../src/cli_version.ts",
);
const PACKAGE_JSON_FILE = path.join(import.meta.dirname, "../package.json");

const RELEASE_URL = "https://github.com/jsr-io/cli/releases/download";

const FILENAMES = [
  "jsr-aarch64-apple-darwin",
  "jsr-x86_64-apple-darwin",
  "jsr-aarch64-unknown-linux-gnu",
  "jsr-x86_64-unknown-linux-gnu",
  "jsr-aarch64-unknown-linux-musl",
  "jsr-x86_64-unknown-linux-musl",
  "jsr-aarch64-pc-windows-msvc",
  "jsr-x86_64-pc-windows-msvc",
];

async function main() {
  const version = process.argv[2];
  if (version === undefined || !version.startsWith("v")) {
    throw new Error("Usage: node scripts/update-cli.ts <tag, e.g. v0.1.0>");
  }

  const pkgJson = JSON.parse(
    await fs.promises.readFile(PACKAGE_JSON_FILE, "utf-8"),
  );
  if (`v${pkgJson.version}` !== version) {
    throw new Error(
      `package.json version ${pkgJson.version} doesn't match ${version}`,
    );
  }

  console.log(`Fetching SHA256 hashes of ${version}...`);
  const hashes = await fetchHashes(version);

  await updateCliVersion(version, hashes);
  console.log("Done!");
}

async function fetchHashes(
  version: string,
): Promise<Record<string, string>> {
  const hashes: Record<string, string> = {};

  for (const name of FILENAMES) {
    const filename = `${name}.zip`;
    const url = `${RELEASE_URL}/${version}/${filename}.sha256sum`;
    const res = await fetch(url);
    if (!res.ok) {
      throw new Error(
        `Failed to fetch hash for ${filename}: ${res.status} ${res.statusText}`,
      );
    }
    const text = (await res.text()).trim();
    // format: "<hash>  <filename>"
    const hash = text.split(/\s+/)[0];
    if (!hash || !/^[0-9a-f]{64}$/.test(hash)) {
      throw new Error(`Invalid hash for ${filename}: ${text}`);
    }
    hashes[filename] = hash;
    console.log(`  ${filename}: ${hash}`);
  }

  return hashes;
}

async function updateCliVersion(
  version: string,
  hashes: Record<string, string>,
): Promise<void> {
  const hashEntries = Object.entries(hashes)
    .map(([filename, hash]) => `    "${filename}": "${hash}",`)
    .join("\n");

  const content =
    `// Generated by scripts/update-cli.ts when publishing to npm, from the
// checksums of the GitHub release.
export const cliVersionInfo = {
  version: "${version}",
  hashes: {
${hashEntries}
  } as Record<string, string>,
};
`;
  await fs.promises.writeFile(CLI_VERSION_FILE, content, "utf-8");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
